CREATE TABLE IF NOT EXISTS permits (
  plate TEXT PRIMARY KEY, permit_type TEXT NOT NULL, status TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS detections (
  id INTEGER PRIMARY KEY AUTOINCREMENT, plate TEXT NOT NULL,
  confidence REAL NOT NULL, permit TEXT NOT NULL, reason TEXT NOT NULL,
  location TEXT NOT NULL, display_time TEXT NOT NULL,
  status TEXT NOT NULL, note TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
